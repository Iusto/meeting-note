CREATE TABLE recordings (
  id UUID PRIMARY KEY, meeting_id UUID NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  state VARCHAR(30) NOT NULL, path TEXT NOT NULL, sha256 VARCHAR(64), bytes BIGINT, duration_ms BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE stream_sessions (
  id UUID PRIMARY KEY, meeting_id UUID NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  provider VARCHAR(40) NOT NULL, provider_session_id VARCHAR(200), audio_offset_ms BIGINT NOT NULL DEFAULT 0,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL, ended_at TIMESTAMP WITH TIME ZONE, close_reason VARCHAR(100)
);
